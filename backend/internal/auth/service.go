var (
	ErrBadEmail       = errors.New("auth: invalid email")
	ErrWeakPassword   = errors.New("auth: password must be 8 to 72 bytes")
	ErrEmailTaken     = errors.New("auth: email already registered")
	ErrBadCredentials = errors.New("auth: wrong email or password")
	ErrNonce          = errors.New("auth: nonce mismatch")
	ErrNotFound       = errors.New("auth: user not found")
	ErrBadInput       = errors.New("auth: invalid input")
)

const bcryptCost = 12

// dummyHash keeps login timing the same whether or not the email exists.
var dummyHash, _ = bcrypt.GenerateFromPassword([]byte("timing-equalizer"), bcryptCost)

type User struct {
	ID            string    `json:"id"`
	Email         string    `json:"email"`
	EmailVerified bool      `json:"email_verified"`
	DisplayName   string    `json:"display_name"`
	AvatarURL     string    `json:"avatar_url"`
	Locale        string    `json:"locale"`
	Country       string    `json:"country"`
	Providers     []string  `json:"providers"`
	CreatedAt     time.Time `json:"created_at"`
}

type Session struct {
	AccessToken  string `json:"access_token"`
	TokenType    string `json:"token_type"`
	ExpiresIn    int    `json:"expires_in"`
	RefreshToken string `json:"refresh_token"`
	User         User   `json:"user"`
}

type Service struct {
	DB       *pgxpool.Pool
	Tokens   *Issuer
	Apple    *Verifier
	Google   *Verifier
	AppleAPI *AppleClient // optional: code exchange + revoke
	Log      *slog.Logger
	Now      func() time.Time
}

func (s *Service) now() time.Time {
	if s.Now != nil {
		return s.Now()
	}
	return time.Now()
}

// ---- email ----

func normalizeEmail(raw string) (string, error) {
	e := strings.ToLower(strings.TrimSpace(raw))
	addr, err := mail.ParseAddress(e)
	if err != nil || addr.Address != e || len(e) > 254 {
		return "", ErrBadEmail
	}
	return e, nil
}

func (s *Service) SignupEmail(ctx context.Context, email, password, name, device string) (Session, error) {
	email, err := normalizeEmail(email)
	if err != nil {
		return Session{}, err
	}
	if len(password) < 8 || len(password) > 72 {
		return Session{}, ErrWeakPassword
	}
	if name, err = cleanText(name, 80); err != nil {
		return Session{}, err
	}
	hash, err := bcrypt.GenerateFromPassword([]byte(password), bcryptCost)
	if err != nil {
		return Session{}, err
	}
	return s.inTx(ctx, func(tx pgx.Tx) (string, error) {
		var userID string
		err := tx.QueryRow(ctx,
			`INSERT INTO users (email, display_name) VALUES ($1, $2) RETURNING id`, email, name,
		).Scan(&userID)
		if isUniqueViolation(err) {
			return "", ErrEmailTaken
		}
		if err != nil {
			return "", err
		}
		_, err = tx.Exec(ctx, `INSERT INTO identities (user_id, provider, subject, email, password_hash)
			VALUES ($1, 'email', $2, $2, $3)`, userID, email, string(hash))
		return userID, err
	}, device)
}

func (s *Service) LoginEmail(ctx context.Context, email, password, device string) (Session, error) {
	email, err := normalizeEmail(email)
	if err != nil {
		return Session{}, ErrBadCredentials
	}
	var userID, hash string
	err = s.DB.QueryRow(ctx,
		`SELECT user_id, password_hash FROM identities WHERE provider = 'email' AND subject = $1`, email,
	).Scan(&userID, &hash)
	if errors.Is(err, pgx.ErrNoRows) {
		_ = bcrypt.CompareHashAndPassword(dummyHash, []byte(password))
		return Session{}, ErrBadCredentials
	}
	if err != nil {
		return Session{}, err
	}
	if bcrypt.CompareHashAndPassword([]byte(hash), []byte(password)) != nil {
		return Session{}, ErrBadCredentials
	}
	return s.newSession(ctx, s.DB, userID, device)
}

// ---- Apple / Google ----

type SocialInput struct {
	IDToken           string
	Nonce             string // raw nonce generated by the app (optional)
	AuthorizationCode string // Apple only: lets us revoke on account deletion
	Name              string // Apple only sends the name to the app, on first sign-in
	Device            string
}

func (s *Service) SignInApple(ctx context.Context, in SocialInput) (Session, error) {
	return s.signInSocial(ctx, s.Apple, in)
}

func (s *Service) SignInGoogle(ctx context.Context, in SocialInput) (Session, error) {
	in.AuthorizationCode = ""
	return s.signInSocial(ctx, s.Google, in)
}

func (s *Service) signInSocial(ctx context.Context, v *Verifier, in SocialInput) (Session, error) {
	claims, err := v.Verify(ctx, in.IDToken)
	if err != nil {
		return Session{}, err
	}
	if !CheckNonce(claims.Nonce, in.Nonce) {
		return Session{}, ErrNonce
	}
	name, err := cleanText(in.Name, 80)
	if err != nil {
		return Session{}, err
	}
	var appleRefresh string
	if v.Provider == "apple" && in.AuthorizationCode != "" && s.AppleAPI != nil {
		if appleRefresh, err = s.AppleAPI.ExchangeCode(ctx, in.AuthorizationCode); err != nil {
			s.log().Warn("apple code exchange", "err", err) // sign-in still works
		}
	}
	email := ""
	if claims.EmailVerified {
		email = strings.ToLower(claims.Email)
	}

	return s.inTx(ctx, func(tx pgx.Tx) (string, error) {
		var userID string
		err := tx.QueryRow(ctx, `SELECT user_id FROM identities WHERE provider = $1 AND subject = $2`,
			v.Provider, claims.Subject).Scan(&userID)
		switch {
		case err == nil: // returning user
			_, err = tx.Exec(ctx, `UPDATE identities SET email = COALESCE(NULLIF($3, ''), email),
				apple_refresh_token = COALESCE(NULLIF($4, ''), apple_refresh_token)
				WHERE provider = $1 AND subject = $2`, v.Provider, claims.Subject, email, appleRefresh)
			return userID, err
		case !errors.Is(err, pgx.ErrNoRows):
			return "", err
		}

		if email != "" {
			userID, err = s.claimByEmail(ctx, tx, email)
			if err != nil {
				return "", err
			}
		}
		if userID == "" {
			err = tx.QueryRow(ctx, `INSERT INTO users (email, email_verified, display_name)
				VALUES (NULLIF($1, ''), $2, $3) RETURNING id`, email, email != "", name).Scan(&userID)
			if err != nil {
				return "", err
			}
		}
		_, err = tx.Exec(ctx, `INSERT INTO identities (user_id, provider, subject, email, apple_refresh_token)
			VALUES ($1, $2, $3, NULLIF($4, ''), NULLIF($5, ''))`, userID, v.Provider, claims.Subject, email, appleRefresh)
		if err == nil && name != "" {
			_, err = tx.Exec(ctx, `UPDATE users SET display_name = $2 WHERE id = $1 AND display_name = ''`, userID, name)
		}
		return userID, err
	}, in.Device)
}

// claimByEmail links a verified social login to an existing account with the
// same email. If that account's email was never verified, someone could have
// registered it first to hijack the real owner later, so the provider wins:
// the password is removed and every session is revoked.
func (s *Service) claimByEmail(ctx context.Context, tx pgx.Tx, email string) (string, error) {
	var userID string
	var verified bool
	err := tx.QueryRow(ctx, `SELECT id, email_verified FROM users WHERE email = $1 FOR UPDATE`, email).
		Scan(&userID, &verified)
	if errors.Is(err, pgx.ErrNoRows) {
		return "", nil
	}
	if err != nil {
		return "", err
	}
	if !verified {
		if _, err := tx.Exec(ctx, `DELETE FROM identities WHERE user_id = $1 AND provider = 'email'`, userID); err != nil {
			return "", err
		}
		if _, err := tx.Exec(ctx, `UPDATE refresh_tokens SET revoked_at = now()
			WHERE user_id = $1 AND revoked_at IS NULL`, userID); err != nil {
			return "", err
		}
		if _, err := tx.Exec(ctx, `UPDATE users SET email_verified = true, updated_at = now() WHERE id = $1`, userID); err != nil {
			return "", err
		}
	}
	return userID, nil
}

// ---- sessions ----

func (s *Service) Refresh(ctx context.Context, token string) (Session, error) {
	tx, err := s.DB.Begin(ctx)
	if err != nil {
		return Session{}, err
	}
	defer tx.Rollback(ctx)

	var userID, familyID, device string
	var expires time.Time
	var revoked *time.Time
	err = tx.QueryRow(ctx, `SELECT user_id, family_id, device_name, expires_at, revoked_at
		FROM refresh_tokens WHERE token_hash = $1 FOR UPDATE`, hashToken(token)).
		Scan(&userID, &familyID, &device, &expires, &revoked)
	if errors.Is(err, pgx.ErrNoRows) {
		return Session{}, ErrInvalidToken
	}
	if err != nil {
		return Session{}, err
	}
	now := s.now()
	if revoked != nil {
		if now.Sub(*revoked) > reuseGrace {
			s.log().Warn("refresh token reuse: revoking family", "user", userID)
			if _, err := tx.Exec(ctx, `UPDATE refresh_tokens SET revoked_at = $2
				WHERE family_id = $1 AND revoked_at IS NULL`, familyID, now); err != nil {
				return Session{}, err
			}
			if err := tx.Commit(ctx); err != nil {
				return Session{}, err
			}
		}
		return Session{}, ErrInvalidToken
	}
	if now.After(expires) {
		return Session{}, ErrInvalidToken
	}
	if _, err := tx.Exec(ctx, `UPDATE refresh_tokens SET revoked_at = $2 WHERE token_hash = $1`, hashToken(token), now); err != nil {
		return Session{}, err
	}
	sess, err := s.issue(ctx, tx, userID, familyID, device)
	if err != nil {
		return Session{}, err
	}
	return sess, tx.Commit(ctx)
}

// Logout ends this device's session (the whole token family).
func (s *Service) Logout(ctx context.Context, token string) error {
	_, err := s.DB.Exec(ctx, `UPDATE refresh_tokens SET revoked_at = now()
		WHERE family_id = (SELECT family_id FROM refresh_tokens WHERE token_hash = $1) AND revoked_at IS NULL`,
		hashToken(token))
	return err
}

type querier interface {
	Exec(ctx context.Context, sql string, args ...any) (pgconn.CommandTag, error)
	QueryRow(ctx context.Context, sql string, args ...any) pgx.Row
	Query(ctx context.Context, sql string, args ...any) (pgx.Rows, error)
}

func (s *Service) newSession(ctx context.Context, q querier, userID, device string) (Session, error) {
	var family string
	if err := q.QueryRow(ctx, `SELECT gen_random_uuid()`).Scan(&family); err != nil {
		return Session{}, err
	}
	device, _ = cleanText(device, 100)
	return s.issue(ctx, q, userID, family, device)
}

func (s *Service) issue(ctx context.Context, q querier, userID, family, device string) (Session, error) {
	access, err := s.Tokens.Issue(userID)
	if err != nil {
		return Session{}, err
	}
	refresh, hash := newRefreshToken()
	if _, err := q.Exec(ctx, `INSERT INTO refresh_tokens (user_id, family_id, token_hash, device_name, expires_at)
		VALUES ($1, $2, $3, $4, $5)`, userID, family, hash, device, s.now().Add(RefreshTTL)); err != nil {
		return Session{}, err
	}
	u, err := loadUser(ctx, q, userID)
	if err != nil {
		return Session{}, err
	}
	return Session{AccessToken: access, TokenType: "Bearer", ExpiresIn: int(AccessTTL.Seconds()),
		RefreshToken: refresh, User: u}, nil
}

// inTx runs fn (which returns the user ID) and opens a session in the same transaction.
func (s *Service) inTx(ctx context.Context, fn func(pgx.Tx) (string, error), device string) (Session, error) {
	tx, err := s.DB.Begin(ctx)
	if err != nil {
		return Session{}, err
	}
	defer tx.Rollback(ctx)
	userID, err := fn(tx)
	if err != nil {
		return Session{}, err
	}
	sess, err := s.newSession(ctx, tx, userID, device)
	if err != nil {
		return Session{}, err
	}
	return sess, tx.Commit(ctx)
}

// ---- account ----

func (s *Service) Me(ctx context.Context, userID string) (User, error) {
	return loadUser(ctx, s.DB, userID)
}

type Patch struct {
	DisplayName *string `json:"display_name"`
	AvatarURL   *string `json:"avatar_url"`
	Locale      *string `json:"locale"`
	Country     *string `json:"country"`
}

func (s *Service) UpdateMe(ctx context.Context, userID string, p Patch) (User, error) {
	fields := []struct {
		col string
		val *string
		max int
	}{{"display_name", p.DisplayName, 80}, {"avatar_url", p.AvatarURL, 500}, {"locale", p.Locale, 16}, {"country", p.Country, 2}}
	for _, f := range fields {
		if f.val == nil {
			continue
		}
		v, err := cleanText(*f.val, f.max)
		if err != nil {
			return User{}, fmt.Errorf("%w: %s", ErrBadInput, f.col)
		}
		if f.col == "country" {
			v = strings.ToUpper(v)
		}
		if _, err := s.DB.Exec(ctx, `UPDATE users SET `+f.col+` = $2, updated_at = now() WHERE id = $1`, userID, v); err != nil {
			return User{}, err
		}
	}
	return s.Me(ctx, userID)
}

// DeleteAccount removes the user and everything that cascades from it, then
// revokes Apple tokens (required by App Review guideline 5.1.1(v)).
func (s *Service) DeleteAccount(ctx context.Context, userID string) error {
	rows, err := s.DB.Query(ctx, `SELECT apple_refresh_token FROM identities
		WHERE user_id = $1 AND apple_refresh_token IS NOT NULL`, userID)
	if err != nil {
		return err
	}
	appleTokens, err := pgx.CollectRows(rows, pgx.RowTo[string])
	if err != nil {
		return err
	}
	tag, err := s.DB.Exec(ctx, `DELETE FROM users WHERE id = $1`, userID)
	if err != nil {
		return err
	}
	if tag.RowsAffected() == 0 {
		return ErrNotFound
	}
	for _, t := range appleTokens {
		if s.AppleAPI == nil {
			break
		}
		if err := s.AppleAPI.Revoke(ctx, t); err != nil {
			s.log().Error("apple revoke on delete", "user", userID, "err", err)
		}
	}
	return nil
}

func loadUser(ctx context.Context, q querier, userID string) (User, error) {
	var u User
	var email *string
	err := q.QueryRow(ctx, `SELECT u.id, u.email, u.email_verified, u.display_name, u.avatar_url, u.locale,
			u.country, u.created_at, COALESCE(array_agg(i.provider ORDER BY i.provider) FILTER (WHERE i.provider IS NOT NULL), '{}')
		FROM users u LEFT JOIN identities i ON i.user_id = u.id
		WHERE u.id = $1 GROUP BY u.id`, userID).
		Scan(&u.ID, &email, &u.EmailVerified, &u.DisplayName, &u.AvatarURL, &u.Locale, &u.Country, &u.CreatedAt, &u.Providers)
	if errors.Is(err, pgx.ErrNoRows) {
		return User{}, ErrNotFound
	}
	if email != nil {
		u.Email = *email
	}
	return u, err
}

func cleanText(s string, max int) (string, error) {
	s = strings.TrimSpace(s)
	if !utf8.ValidString(s) || utf8.RuneCountInString(s) > max || strings.ContainsAny(s, "\x00\r\n") {
		return "", ErrBadInput
	}
	return s, nil
}

func isUniqueViolation(err error) bool {
	var pg *pgconn.PgError
	return errors.As(err, &pg) && pg.Code == "23505"
}

func (s *Service) log() *slog.Logger {
	if s.Log != nil {
		return s.Log
	}
	return slog.Default()
}
